#!/bin/bash
# Find out why Vivado / Vitis do not work on Titan's compute nodes — run it on THIS machine:
#
#   bash tests/live/titan_diagnose.sh            # ssh host "titan" from ~/.ssh/config
#   bash tests/live/titan_diagnose.sh titan
#
# It needs nothing from my-system. It sends ONE Slurm job (4 CPUs, at most 2 hours) that, on a node:
#   - checks the node (OS, glibc, locale, /tmp, the share and how it is mounted),
#   - checks the link ~/ACCOUNT/xilinx -> share and that the node can reach the head node (scp),
#   - sources Vivado's and Vitis' settings64.sh and looks at PATH, execute bits and missing libraries,
#   - starts vivado / vitis-run / v++ / vitis_hls / xelab,
#   - really synthesizes a tiny Verilog design with Vivado and a tiny C++ function with HLS.
# Everything it writes stays in your own folders: /mnt/perflab/ACCOUNT/diag-TIME (removed at the end, unless
# KEEP=1) and a temporary folder on the node. The full report is saved here as titan-diagnose-TIME.txt.
#
# Settings (environment variables), defaults from docs/remote-servers.md:
#   ACCOUNT=benyamin PARTITION=batch QOS=batch_qos VER=2025.2.1 HEAD=bacchus PART=xc7z020clg400-1
#   SHARE=/mnt/perflab           (the share as the nodes and the head node see it)
#   WAIT_MIN=120                 (how long to wait for the job, including time in the Slurm queue)
set -u
HOST="${1:-titan}"
ACCOUNT="${ACCOUNT:-benyamin}"
PARTITION="${PARTITION:-batch}"
QOS="${QOS:-batch_qos}"
VER="${VER:-2025.2.1}"
HEAD="${HEAD:-bacchus}"
PART="${PART:-xc7z020clg400-1}"
SHARE="${SHARE:-/mnt/perflab}"
WAIT_MIN="${WAIT_MIN:-120}"
KEEP="${KEEP:-0}"
TS="$(date +%Y%m%d-%H%M%S)"
OUT="titan-diagnose-$TS.txt"

for v in "$ACCOUNT" "$PARTITION" "$QOS" "$VER" "$HEAD" "$PART"; do
  case "$v" in *[!A-Za-z0-9._-]*|"") echo "unsafe or empty setting: '$v'"; exit 2;; esac
done
case "$SHARE" in /*) ;; *) echo "SHARE must be an absolute path"; exit 2;; esac
D="$SHARE/$ACCOUNT/diag-$TS"                       # result folder on the share (head node and nodes both see it)
SSH=(ssh -o BatchMode=yes -o ConnectTimeout=20 "$HOST")

say() { echo "$*" | tee -a "$OUT"; }
say "Titan diagnose $TS — host $HOST, account $ACCOUNT, tools $VER, part $PART"
say ""

# ------------------------------------------------------------------ 1. from here to the head node
if ! hn=$("${SSH[@]}" hostname 2>&1); then
  say "NO  ssh $HOST: $hn"
  say "    fix: VPN on? key installed? first time: ssh -o StrictHostKeyChecking=accept-new $HOST hostname"
  exit 1
fi
say "ok  ssh $HOST -> $hn"

# ------------------------------------------------------------------ 2. on the head node
"${SSH[@]}" "bash -s" > >(tee -a "$OUT") 2>&1 <<EOF
A=$ACCOUNT; V=$VER; S=$SHARE
echo "== head node \$(hostname)"
for t in sbatch squeue sacct; do command -v \$t >/dev/null || echo "NO  \$t not found on the head node"; done
loc="\$HOME/\$A/xilinx/\$V"; sh="\$S/\$A/xilinx/\$V"
[ -d "\$loc" ] && echo "ok  installation on the head node's own disk: \$loc" || echo "..  no installation at \$loc (fine if it only lives on the share)"
if [ -d "\$sh" ]; then
  echo "ok  copy on the share: \$sh (\$(du -sh "\$sh" 2>/dev/null | cut -f1))"
  for p in Vivado Vitis; do
    [ -f "\$sh/\$p/settings64.sh" ] && echo "ok  \$p/settings64.sh on the share" || echo "NO  \$p/settings64.sh missing on the share"
  done
  b="\$sh/Vivado/bin/unwrapped/lnx64.o/vivado"
  if [ -e "\$b" ]; then [ -x "\$b" ] && echo "ok  vivado binary on the share is executable" \\
      || echo "NO  vivado binary on the share is NOT executable (copy lost the x bit: rsync -rltp, or the mount's file_mode)"
  else echo "NO  \$b missing on the share (copy incomplete?)"; fi
  nx=\$(find "\$sh/Vivado/bin" "\$sh/Vitis/bin" -maxdepth 1 -type f ! -perm -u+x 2>/dev/null | head -5)
  [ -n "\$nx" ] && echo "NO  not executable on the share, e.g.: \$(echo \$nx)"
else
  echo "NO  no copy on the share at \$sh — the nodes cannot see the tools"
fi
[ -f "\$S/\$A/installers/rsync.log" ] && { n=\$(grep -c . "\$S/\$A/installers/rsync.log"); echo "..  rsync.log: \$n lines; last:"; tail -3 "\$S/\$A/installers/rsync.log" | sed 's/^/      /'; }
echo "..  mount of the share here: \$(findmnt -n -o FSTYPE,OPTIONS -T "\$S" 2>/dev/null | cut -c1-200)"
mkdir -p "$D" || { echo "NO  cannot create $D"; exit 3; }
EOF
[ "${PIPESTATUS[0]}" = 3 ] && exit 1

# ------------------------------------------------------------------ 3. the job that runs on a node
NODE_SH=$(cat <<'NODE_EOF'
#!/bin/bash
# generated by titan_diagnose.sh
cd "$(mktemp -d "${TMPDIR:-/tmp}/diag-XXXXXX")" || { echo "R workdir=fail"; exit 90; }
WD=$PWD
r() { echo "R $1=$2"; }                      # result lines, summarized at the end
sec() { echo; echo "== $*"; }
sec "node"
echo "host=$(hostname) cpus=$(nproc) os=$( . /etc/os-release; echo "$PRETTY_NAME") glibc=$(ldd --version | head -1 | awk '{print $NF}')"
free -g | sed -n 1,2p
echo "tmp: $(df -h "${TMPDIR:-/tmp}" | tail -1)"
sec "locale (sent along by ssh/sbatch)"
echo "LANG=${LANG:-} LC_ALL=${LC_ALL:-} LC_CTYPE=${LC_CTYPE:-}"
lw=$(locale 2>&1 >/dev/null)
if [ -n "$lw" ]; then echo "$lw"; r locale bad; ORIG_LANG=${LANG:-}; ORIG_LC_ALL=${LC_ALL:-}; else r locale ok; fi
sec "share $SHARE"
findmnt -n -o SOURCE,FSTYPE,OPTIONS -T "$SHARE" 2>/dev/null | cut -c1-250 || true
if [ -d "$SHARE/$A" ]; then r share ok; else r share missing; echo "the share is not mounted on this node"; fi
sec "link ~/$A/xilinx -> $SHARE/$A/xilinx"
L="$HOME/$A/xilinx"
if [ -L "$L" ]; then echo "link -> $(readlink "$L")"; [ "$(readlink "$L")" = "$SHARE/$A/xilinx" ] && r link ok || r link other
elif [ -e "$L" ]; then echo "a REAL folder/file is at $L (so a link cannot be made):"; ls -la "$L" | head -5; r link realdir
else mkdir -p "$(dirname "$L")" && ln -s "$SHARE/$A/xilinx" "$L" && echo "link made" && r link made; fi
[ -d "$L/$V" ] && r install_visible yes || r install_visible no
sec "can this node reach the head node? (my-system fetches job files with scp when there is no shared disk)"
if out=$(ssh -o BatchMode=yes -o ConnectTimeout=10 "$H" true 2>&1); then r head_ssh ok; echo "ssh $H ok"
else r head_ssh fail; echo "ssh $H failed: $out"; ls -la ~/.ssh 2>/dev/null | head; fi
sec "settings files"
for p in Vivado Vitis; do
  f="$L/$V/$p/settings64.sh"
  if [ ! -f "$f" ]; then echo "$p: $f missing"; r "settings_$p" missing; continue; fi
  ( unset LANGUAGE; export LANG=C.UTF-8 LC_ALL=C.UTF-8
    # shellcheck disable=SC1090
    source "$f" >/dev/null 2>&1
    echo "$p settings: XILINX_VIVADO=${XILINX_VIVADO:-} XILINX_VITIS=${XILINX_VITIS:-} XILINX_HLS=${XILINX_HLS:-}"
    for t in vivado vitis-run v++ vitis_hls xelab; do
      pth=$(command -v $t || true)
      if [ -z "$pth" ]; then echo "  $t: not on PATH"; echo "R path_${p}_$t=no"
      else x=$(readlink -f "$pth"); [ -x "$x" ] && e="exec" || e="NOT-EXECUTABLE"; echo "  $t: $pth ($e)"; echo "R path_${p}_$t=$e"; fi
    done )
done
ST="$L/$V/Vitis/settings64.sh"; [ -f "$ST" ] || ST="$L/$V/Vivado/settings64.sh"
if [ ! -f "$ST" ]; then r settings none; echo "no settings64.sh: stop"; exit 0; fi
sec "C library files and installed devices ($ST)"
( source "$ST" >/dev/null 2>&1
  [ -e /usr/lib/x86_64-linux-gnu/crt1.o ] && [ -e /usr/include/stdio.h ] && echo "R libc_dev=yes" || echo "R libc_dev=no"
  ls "${XILINX_VIVADO:-/nonexistent}/data/parts/xilinx" 2>/dev/null | tr '\n' ' ' | sed 's/^/parts: /'; echo )
if [ -n "${ORIG_LANG+x}" ]; then
  sec "vivado with the ORIGINAL (broken) locale — shows whether the locale is the problem"
  ( export LANG="$ORIG_LANG"; [ -n "$ORIG_LC_ALL" ] && export LC_ALL="$ORIG_LC_ALL"
    source "$ST" >/dev/null 2>&1; timeout 600 vivado -version 2>&1 | head -5; echo "R vivado_orig_locale=${PIPESTATUS[0]}" )
fi
unset LANGUAGE; export LANG=C.UTF-8 LC_ALL=C.UTF-8
# shellcheck disable=SC1090
source "$ST" >/dev/null 2>&1
run() { local n=$1; shift; command -v "$1" >/dev/null || { r "start_$n" absent; return; }
  sec "$*"; mkdir -p "$WD/v_$n"; local o rc; o=$(cd "$WD/v_$n" && timeout 900 "$@" < /dev/null 2>&1); rc=$?
  printf '%s\n' "$o" | tail -8; r "start_$n" "$rc"; }
run vivado vivado -version
run vitis-run vitis-run --version
run v++ v++ --version
run vitis_hls vitis_hls -version
run xelab xelab -version
sec "real Vivado synthesis ($P)"
mkdir -p "$WD/syn" && cd "$WD/syn" && cat > top.v <<'V'
module top(input clk, input rst, output reg [7:0] q);
  always @(posedge clk) if (rst) q <= 0; else q <= q + 1;
endmodule
V
cat > syn.tcl <<T
read_verilog top.v
synth_design -top top -part $P
report_utilization -file util.rpt
T
if command -v vivado >/dev/null; then
  timeout 1800 vivado -mode batch -nojournal -source syn.tcl > syn.log 2>&1; rc=$?
  grep -E "^(ERROR|CRITICAL WARNING)" syn.log | head -8
  tail -4 syn.log
  if [ $rc = 0 ] && [ -s util.rpt ]; then r vivado_synth ok; else r vivado_synth "fail(rc=$rc)"; fi
else r vivado_synth "no-vivado"; fi
sec "real HLS C synthesis ($P)"
mkdir -p "$WD/hls" && cd "$WD/hls" && cat > add.cpp <<'C'
int add(int a, int b) { return a + b; }
C
cat > hls.tcl <<T
open_project -reset p
set_top add
add_files add.cpp
open_solution -reset s -flow_target vivado
set_part $P
create_clock -period 10
csynth_design
exit
T
if command -v vitis-run >/dev/null; then timeout 1800 vitis-run --mode hls --tcl hls.tcl > hls.log 2>&1; rc=$?; how=vitis-run
elif command -v vitis_hls >/dev/null; then timeout 1800 vitis_hls -f hls.tcl > hls.log 2>&1; rc=$?; how=vitis_hls
else rc=127; how=none; echo "no vitis-run and no vitis_hls on PATH"; fi
grep -E "^(ERROR|CRITICAL WARNING)" hls.log 2>/dev/null | head -8
tail -4 hls.log 2>/dev/null
if [ "$how" != none ] && find . -name csynth.xml | grep -q .; then r hls_synth "ok($how)"; else r hls_synth "fail($how,rc=$rc)"; fi
cd /; rm -rf "$WD"
sec "done $(date '+%F %T')"
NODE_EOF
)
HDR="A=$ACCOUNT V=$VER H=$HEAD P=$PART SHARE=$SHARE"
"${SSH[@]}" "cat > '$D/node.sh'" <<<"$(printf '%s\n' "#!/bin/bash" "$HDR" "${NODE_SH#\#!/bin/bash}")" || { say "NO  cannot write the job"; exit 1; }
SID=$("${SSH[@]}" "sbatch --parsable --job-name=diag-$ACCOUNT --account=$ACCOUNT --partition=$PARTITION --qos=$QOS \
  --cpus-per-task=4 --time=02:00:00 --chdir=/tmp --output='$D/slurm.out' '$D/node.sh'" 2>&1)
SID="${SID%%;*}"
case "$SID" in ''|*[!0-9]*) say "NO  sbatch failed: $SID"; exit 1;; esac
say ""; say "submitted Slurm job $SID; waiting (at most $WAIT_MIN min). Ctrl-C cancels it."
trap '"${SSH[@]}" "scancel --account=$ACCOUNT $SID" >/dev/null 2>&1; echo; echo "cancelled"; exit 130' INT TERM
last=""; t0=$(date +%s)
while :; do
  st=$("${SSH[@]}" "squeue -h -j $SID -o '%T %N %r' 2>/dev/null; true" 2>/dev/null)
  if [ -z "$st" ]; then
    acct=$("${SSH[@]}" "sacct -n -X -P -j $SID -o State,ExitCode,NodeList 2>/dev/null | head -1; true" 2>/dev/null)
    case "$acct" in RUNNING*|PENDING*|"") ;; *) break;; esac
  elif [ "$st" != "$last" ]; then echo "  $(date +%T) $st"; last="$st"; fi
  if [ $(( $(date +%s) - t0 )) -gt $(( WAIT_MIN * 60 )) ]; then
    say "still not finished after $WAIT_MIN min — cancelling"; "${SSH[@]}" "scancel --account=$ACCOUNT $SID"; break; fi
  sleep 15
done
say "Slurm: ${acct:-?}"

# ------------------------------------------------------------------ 4. report
LOG=$("${SSH[@]}" "cat '$D/slurm.out' 2>/dev/null")
if [ -z "$LOG" ]; then
  say "NO  the job wrote nothing to $D/slurm.out — the share is probably not mounted on node ${acct##*|}"
else
  echo "$LOG" >> "$OUT"
fi
val() { echo "$LOG" | sed -n "s/^R $1=//p" | tail -1; }
say ""
say "================ SUMMARY ================"
chk() { if [ "$1" = ok ]; then say "ok  $2"; else say "NO  $2"; [ -n "${3:-}" ] && say "    -> $3"; fi; }
[ -n "$LOG" ] && {
  chk "$( [ "$(val share)" = ok ] && echo ok)" "share mounted on the node" "ask the admins: $SHARE is not mounted on that node"
  case "$(val link)" in
    ok|made) say "ok  link ~/$ACCOUNT/xilinx on the node";;
    realdir) say "NO  a real folder sits at ~/$ACCOUNT/xilinx on the node (no link possible)"
             say "    -> on that node: check it is yours, then remove it (my-system makes the link again)";;
    other)   say "NO  ~/$ACCOUNT/xilinx on the node links somewhere else";;
  esac
  chk "$( [ "$(val install_visible)" = yes ] && echo ok)" "the tools ($VER) are visible on the node" "copy to the share incomplete, or a different folder name"
  chk "$( [ "$(val head_ssh)" = ok ] && echo ok)" "the node can ssh/scp to $HEAD" \
      "my-system jobs end with exit 92: put the key + known_hosts for $HEAD in that node's ~/.ssh (each node has its own home)"
  [ "$(val locale)" = bad ] && say "!!  the locale sent from here does not exist on the node (my-system 1.18 fixes this: C.UTF-8)" \
      && [ -n "$(val vivado_orig_locale)" ] && say "    vivado with that locale: exit $(val vivado_orig_locale)"
  for p in Vivado Vitis; do
    for t in vivado vitis-run v++; do
      x=$(val "path_${p}_$t"); [ "$x" = NOT-EXECUTABLE ] && say "NO  $t is not executable ($p settings) -> copy again with rsync -rltp"
    done
  done
  [ "$(val path_Vivado_vivado)" = exec ] && [ "$(val path_Vivado_vitis-run)" = no ] && [ "$(val path_Vitis_vitis-run)" = exec ] && \
    say "!!  Vivado/settings64.sh has no HLS: use  setup = source ~/$ACCOUNT/xilinx/$VER/Vitis/settings64.sh"
  for t in vivado vitis-run v++ vitis_hls xelab; do
    s=$(val "start_$t"); case "$s" in 0) say "ok  $t starts";; absent|"") say "..  $t not available";;
      124) say "NO  $t did not answer within 15 min (share too slow?)";;
      *) say "NO  $t exits with $s"; m=$(echo "$LOG" | grep -o 'error while loading shared libraries: [^:]*' | head -1)
         [ -n "$m" ] && say "    -> $m: ask the admins, or put it in ~/$ACCOUNT/lib and add LD_LIBRARY_PATH to setup";;
    esac
  done
  chk "$( [ "$(val vivado_synth)" = ok ] && echo ok)" "Vivado synthesizes a design for $PART ($(val vivado_synth))" "see 'real Vivado synthesis' in the report"
  case "$(val hls_synth)" in ok*) say "ok  HLS C synthesis works ($(val hls_synth))";; *) say "NO  HLS C synthesis: $(val hls_synth) -> see 'real HLS' in the report";; esac
  [ "$(val libc_dev)" = no ] && say "..  no libc6-dev on the node: HLS C simulation (csim) cannot link; csynth is fine"
}
say ""
say "full report: $PWD/$OUT"
if [ "$KEEP" != 1 ]; then
  "${SSH[@]}" "case '$D' in */$ACCOUNT/diag-[0-9]*-[0-9]*) rm -rf '$D';; esac"
fi
